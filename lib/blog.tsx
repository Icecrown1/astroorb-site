/**
 * Блог: статьи как структурированные данные (без MDX-зависимостей).
 * Инлайн-разметка в абзацах: **жирный** и [ссылка](/path).
 * Астрономические даты в статьях рассчитаны по Swiss Ephemeris (МСК).
 */

export type Block =
  | { type: "h2"; text: string }
  | { type: "p"; text: string }
  | { type: "list"; items: string[] }
  | { type: "table"; head: string[]; rows: string[][] }
  | { type: "cta"; label: string; text: string; ctaId: string };

export interface Article {
  slug: string;
  title: string;
  h1: string;
  description: string;
  date: string; // ISO
  minutes: number;
  tag: string;
  blocks: Block[];
}

/** **жирный** и [текст](/url) → React-ноды. */
export function inline(text: string): React.ReactNode[] {
  const out: React.ReactNode[] = [];
  const re = /\*\*([^*]+)\*\*|\[([^\]]+)\]\(([^)]+)\)/g;
  let last = 0;
  let m: RegExpExecArray | null;
  let k = 0;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push(text.slice(last, m.index));
    if (m[1]) out.push(<strong key={k++} className="font-semibold text-ink">{m[1]}</strong>);
    else if (m[2] && m[3]?.startsWith("/"))
      out.push(
        <Link key={k++} href={m[3]} className="text-iris underline decoration-iris/40 underline-offset-4 hover:decoration-iris">
          {m[2]}
        </Link>,
      );
    else out.push(m[2] || "");
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}

