/* ---------- Расчёт знака Венеры (astronomy-engine, браузер и сервер) ---------- */

function venusLonAt(utc: Date): number {
  const ecl = Ecliptic(GeoVector(Body.Venus, MakeTime(utc), true));
  return ((ecl.elon % 360) + 360) % 360;
}

export function venusSignAt(utc: Date): Sign {
  return signByLongitude(venusLonAt(utc));
}

export type VenusDayResult =
  | { kind: "single"; sign: Sign }
  | { kind: "switch"; before: Sign; after: Sign; switchLocal: string };

/**
 * Знак Венеры для даты рождения. Венера проходит не больше ~1,3° в сутки,
 * поэтому за день возможен максимум один переход; время нужно только в этот день.
 */
export function venusForBirth(dateISO: string, timeHHMM: string | null, tzHours: number): VenusDayResult {
  const [y, m, d] = dateISO.split("-").map(Number);
  const localToUtc = (minutes: number) => new Date(Date.UTC(y, m - 1, d, 0, minutes) - tzHours * 3600 * 1000);

  if (timeHHMM) {
    const [hh, mm] = timeHHMM.split(":").map(Number);
    return { kind: "single", sign: venusSignAt(localToUtc(hh * 60 + mm)) };
  }

  const start = venusSignAt(localToUtc(0));
  const end = venusSignAt(localToUtc(24 * 60 - 1));
  if (start.slug === end.slug) return { kind: "single", sign: start };

  let lo = 0;
  let hi = 24 * 60 - 1;
  while (hi - lo > 1) {
    const mid = Math.floor((lo + hi) / 2);
    if (venusSignAt(localToUtc(mid)).slug === start.slug) lo = mid;
    else hi = mid;
  }
  const hh = String(Math.floor(hi / 60)).padStart(2, "0");
  const mm = String(hi % 60).padStart(2, "0");
  return { kind: "switch", before: start, after: end, switchLocal: `${hh}:${mm}` };
}
