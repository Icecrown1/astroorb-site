/** Лунная совместимость по положению знаков: та же стихия, союзная стихия, квадрат. */
const ALLY: Record<Sign["element"], Sign["element"]> = { fire: "air", air: "fire", earth: "water", water: "earth" };

export function moonRelations(slug: string) {
  const idx = SIGNS.findIndex((s) => s.slug === slug);
  const me = SIGNS[idx];
  const same = SIGNS.filter((s) => s.element === me.element && s.slug !== slug);
  const allied = SIGNS.filter((s) => s.element === ALLY[me.element]);
  const square = [SIGNS[(idx + 3) % 12], SIGNS[(idx + 9) % 12]];
  return { same, allied, square };
}

/* ---------- Расчёт знака Луны (astronomy-engine, браузер и сервер) ---------- */

function moonLonAt(utc: Date): number {
  const ecl = Ecliptic(GeoVector(Body.Moon, MakeTime(utc), true));
  return ((ecl.elon % 360) + 360) % 360;
}

export function moonSignAt(utc: Date): Sign {
  return signByLongitude(moonLonAt(utc));
}

export type MoonDayResult =
  | { kind: "single"; sign: Sign }
  | { kind: "switch"; before: Sign; after: Sign; switchLocal: string };

/**
 * Знак Луны для даты рождения.
 * Время известно → точный знак. Не известно → если Луна сменила знак в этот день,
 * возвращает оба знака и местное время перехода (Луна проходит ~13° в сутки,
 * поэтому за день возможен максимум один переход).
 */
export function moonForBirth(dateISO: string, timeHHMM: string | null, tzHours: number): MoonDayResult {
  const [y, m, d] = dateISO.split("-").map(Number);
  const localToUtc = (minutes: number) => new Date(Date.UTC(y, m - 1, d, 0, minutes) - tzHours * 3600 * 1000);

  if (timeHHMM) {
    const [hh, mm] = timeHHMM.split(":").map(Number);
    return { kind: "single", sign: moonSignAt(localToUtc(hh * 60 + mm)) };
  }

  const start = moonSignAt(localToUtc(0));
  const end = moonSignAt(localToUtc(24 * 60 - 1));
  if (start.slug === end.slug) return { kind: "single", sign: start };

  let lo = 0;
  let hi = 24 * 60 - 1;
  while (hi - lo > 1) {
    const mid = Math.floor((lo + hi) / 2);
    if (moonSignAt(localToUtc(mid)).slug === start.slug) lo = mid;
    else hi = mid;
  }
  const hh = String(Math.floor(hi / 60)).padStart(2, "0");
  const mm = String(hi % 60).padStart(2, "0");
  return { kind: "switch", before: start, after: end, switchLocal: `${hh}:${mm}` };
}
